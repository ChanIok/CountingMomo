#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const readJson = (relative) => JSON.parse(fs.readFileSync(path.join(root, relative), "utf8"));
const zh = readJson("src/locales/zh-CN.json");
const en = readJson("src/locales/en-US.json");
const keys = Object.keys(zh).sort();

function fail(message) {
  throw new Error(message);
}

function placeholders(value, key) {
  const stripped = value.replace(/\{\d+\}/g, "");
  if (/[{}]/.test(stripped)) fail(`${key}: use numbered placeholders such as {0}`);
  const indices = [...new Set([...value.matchAll(/\{(\d+)\}/g)].map((match) => Number(match[1])))].sort((a, b) => a - b);
  if (indices.some((value, index) => value !== index)) fail(`${key}: placeholder indices must start at 0 and be consecutive`);
  return indices.join(",");
}

if (JSON.stringify(keys) !== JSON.stringify(Object.keys(en).sort())) {
  fail("zh-CN and en-US must define exactly the same keys");
}
for (const key of keys) {
  if (!/^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$/.test(key)) fail(`Invalid text key: ${key}`);
  for (const texts of [zh, en]) {
    if (typeof texts[key] !== "string" || texts[key].trim() === "") fail(`${key}: text must be a nonempty string`);
  }
  if (placeholders(zh[key], key) !== placeholders(en[key], key)) fail(`${key}: placeholder mismatch between languages`);
}

function requireKey(key, source) {
  if (!Object.hasOwn(zh, key)) fail(`${source}: missing text key ${key}`);
}

// Dynamic category/group keys are checked against the generated table by navigation's static_assert.
// Validate direct literal references in C++ sources here.
function inspectSources(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === "generated") continue;
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) inspectSources(file);
    else if (/\.(cpp|hpp)$/.test(entry.name)) {
      const source = fs.readFileSync(file, "utf8");
      const reference = /(?:core::(?:error|message|text_key)|core::i18n::wide)\(\s*(?:state,\s*)?"([a-z][a-z0-9_.]+)"(?!\s*\+)/g;
      for (const match of source.matchAll(reference)) requireKey(match[1], path.relative(root, file));
    }
  }
}
inspectSources(path.join(root, "src"));

// JSON string escaping is also valid for these UTF-8 C++ string literals.
const entries = keys.map((key) => `    {${JSON.stringify(key)}, ${JSON.stringify(zh[key])}, ${JSON.stringify(en[key])}},`).join("\n");
const header = `#pragma once
// Generated by scripts/generate-locales.js. Edit src/locales/*.json instead.
#include "vendor/std.hpp"

namespace core::i18n::generated {
struct Text {
  std::string_view key;
  std::string_view zh_cn;
  std::string_view en_us;
};
inline constexpr std::array<Text, ${keys.length}> texts{{
${entries}
}};
}  // namespace core::i18n::generated
`;
const destination = path.join(root, "src/core/i18n/generated/texts.hpp");
fs.mkdirSync(path.dirname(destination), { recursive: true });
// Preserve the timestamp when regeneration leaves the content unchanged.
if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== header) {
  fs.writeFileSync(destination, header, "utf8");
}
console.log(`Generated ${keys.length} bilingual text entries.`);
